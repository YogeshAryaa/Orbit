import {Router} from 'express';import {createConversation,listConversations,getMessages,updateGroup,addMembers,removeMember,leaveGroup,setConversationFlag,setMessagePin,promoteAdmin,demoteAdmin,getConversationAccess,updateConversationAccess,updateGroupAccess,authorizeConversationDevice} from '../controllers/conversationController.js';import {searchMessages} from '../controllers/messageController.js';import {requireAuth} from '../middleware/auth.js';import {validate} from '../middleware/validate.js';import {conversationSchema,pageSchema} from '../validators/schemas.js';
import {asyncHandler} from '../utils/asyncHandler.js';
const r=Router();
r.use(requireAuth);
r.get('/',asyncHandler(listConversations));
r.post('/',validate(conversationSchema),asyncHandler(createConversation));
r.get('/:id/messages',validate(pageSchema),asyncHandler(getMessages));
r.get('/:id/access',asyncHandler(getConversationAccess));
r.patch('/:id/access',asyncHandler(updateConversationAccess));
r.patch('/:id/access/group',asyncHandler(updateGroupAccess));
r.post('/:id/access/authorize-device',asyncHandler(authorizeConversationDevice));
r.get('/:id/search',asyncHandler(searchMessages));
r.patch('/:id/group',asyncHandler(updateGroup));
r.post('/:id/members',asyncHandler(addMembers));
r.delete('/:id/members/:memberId',asyncHandler(removeMember));
r.post('/:id/leave',asyncHandler(leaveGroup));
r.post('/:id/admins/:memberId',asyncHandler(promoteAdmin));
r.delete('/:id/admins/:memberId',asyncHandler(demoteAdmin));
r.patch('/:id/pin',(req,res,next)=>{req.params.action='pin';next();},asyncHandler(setConversationFlag));
r.patch('/:id/archive',(req,res,next)=>{req.params.action='archive';next();},asyncHandler(setConversationFlag));
export default r;
